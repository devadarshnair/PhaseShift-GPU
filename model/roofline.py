# Bytes per transfer of one DRAM channel in the SimX memory model (third_party/vortex/docs/simulation.md:193,198-200:
# "HBM 16 B, GDDR6 2 B per transfer"; sim/common/dram_sim.cpp:152-160 sets a 128-bit HBM channel).
DRAM_BYTES_PER_TRANSFER = {"HBM2": 16, "HBM2E": 16, "HBM3": 16, "GDDR6": 2}
VX_CONFIG = PS_ROOT / "third_party" / "vortex" / "VX_config.toml"


def dram_peak_bw(num_banks: int, mem_type: str, data_rate_mts: float) -> float:
    """Peak DRAM bandwidth of the SimX memory model, bytes/s (docs/simulation.md:198-200): channels × channel width ×
    data rate, with one channel per memory bank (VX_CFG_PLATFORM_MEMORY_NUM_BANKS), width 16 B per transfer for HBM
    and 2 B for GDDR6, and VX_CFG_PLATFORM_MEMORY_DATA_RATE in MT/s. VX_CFG_PLATFORM_MEMORY_PEAK_BW is NOT this
    number: it is the platform figure the runtime reports (simulation.md:200-201)."""
    return num_banks * DRAM_BYTES_PER_TRANSFER[mem_type] * data_rate_mts * 1e6


def vortex_platform_defaults(path: Path = VX_CONFIG) -> dict:
    """Read the default platform-memory keys from VX_config.toml (read-only): NUM_BANKS, MEMORY_TYPE, CLOCK_RATE
    (MHz) and DATA_RATE (MT/s), whose default is the expression `2 * $VX_CFG_PLATFORM_CLOCK_RATE` (:94) — the only
    expression form accepted here; anything else raises so a changed config is noticed."""
    import re
    import tomllib
    pm = tomllib.loads(path.read_text())["platform_memory"]
    clock = float(pm["VX_CFG_PLATFORM_CLOCK_RATE"])
    rate = pm["VX_CFG_PLATFORM_MEMORY_DATA_RATE"]
    if isinstance(rate, str):
        m = re.fullmatch(r"expr:\s*(\d+(?:\.\d+)?)\s*\*\s*\$VX_CFG_PLATFORM_CLOCK_RATE", rate.strip())
        if not m:
            raise ValueError(f"unexpected VX_CFG_PLATFORM_MEMORY_DATA_RATE {rate!r}")
        rate = float(m.group(1)) * clock
    return dict(num_banks=int(pm["VX_CFG_PLATFORM_MEMORY_NUM_BANKS"]), mem_type=pm["VX_CFG_PLATFORM_MEMORY_TYPE"],
                clock_mhz=clock, data_rate_mts=float(rate),
                runtime_peak_bw_mb_s=float(pm["VX_CFG_PLATFORM_MEMORY_PEAK_BW"]))


def vortex_s1(cores: int, threads: int = 32, warps: int = 8) -> Machine:
    """UNMEASURED Vortex placeholder (replaces it). Derivation from third_party/vortex/VX_config.toml:
    ISSUE_WIDTH = up(NUM_WARPS/16) (:58) = 1 for 8 warps; FPU lanes = SIMD width = NUM_THREADS (:59, :127), FPU blocks
    = ISSUE_WIDTH (:128), one FMA (2 FLOP) per lane per cycle -> 2·threads FLOP/cycle/core (FP32).
    TCU (assumption): blocks = ISSUE_WIDTH (:295); per block an FEDP grid of TC_M × TC_N elements, each a TC_K-word
    dot product (docs/designs/tensor_core_wgmma_engine.md §5.3, VX_tcu_pkg.sv:66-74: block capacity NUM_THREADS words,
    TC_M ≥ TC_N the most nearly square power-of-two split, TC_K = capacity / TC_M); FP16 packs 2 elements per word.
    Assuming one grid issue per cycle (the grid free-runs, doc §5.4) gives 2·TC_M·TC_N·(2·TC_K) FLOP/cycle/block
    (NT = 32: 8·4·8 = 256 FMA = 512 FLOP). This is a structural upper bound, not a measured rate.
    DRAM: the SimX model's peak from the default keys (`dram_peak_bw`, `vortex_platform_defaults`): 2 HBM2 channels
    (:80, :93) × 16 B × 800 MT/s (= 2 × the 400 MHz core clock, :85, :94) = 25.6 GB/s = 64 B per core cycle — the
    "one 64 B block per cycle" of the comment at :86-92 / simulation.md:203-205 is for the whole memory, not per
    channel. Independent of the core count. VX_CFG_PLATFORM_MEMORY_PEAK_BW = 460 GB/s (:84) is only what the runtime
    reports, not the simulated DRAM. Still unmeasured (achievable bandwidth is below peak; measures it)."""
    issue = max(1, math.ceil(warps / 16))
    lg = int(math.log2(threads))
    tc_m, tc_n = 1 << (lg - lg // 2), 1 << (lg // 2)
    tc_k = threads // max(tc_m, tc_n)
    fpu = 2 * threads * issue
    tcu = 2 * tc_m * tc_n * (2 * tc_k) * issue
    pd = vortex_platform_defaults()
    clk = pd["clock_mhz"] * 1e6
    bw = dram_peak_bw(pd["num_banks"], pd["mem_type"], pd["data_rate_mts"])
    return Machine(
        name=f"vortex-S1-{cores}c", clock_hz=clk, flops_per_cycle={"fpu": cores * fpu, "tcu": cores * tcu},
        dram_bytes_per_cycle=bw / clk, measured=False,
        sources={"fpu": f"unmeasured: VX_config.toml:58,59,127,128 (NT={threads}, NW={warps}, issue width {issue}), "
                        f"1 FMA/lane/cycle",
                 "tcu": f"assumption (unmeasured): FEDP grid {tc_m}x{tc_n}x{2 * tc_k} FP16 MAC/cycle/block, one issue "
                        f"per cycle (tensor_core_wgmma_engine.md §5.3-5.4, VX_tcu_pkg.sv:66-74, VX_config.toml:295)",
                 "dram_bytes_per_cycle": f"unmeasured peak of the SimX DRAM model: {pd['num_banks']} {pd['mem_type']} "
                        f"channels x {DRAM_BYTES_PER_TRANSFER[pd['mem_type']]} B x {pd['data_rate_mts']:.0f} MT/s / "
                        f"{pd['clock_mhz']:.0f} MHz (VX_config.toml:80,85,93,94; docs/simulation.md:198-205; "
                        f"dram_sim.cpp:152-160); PEAK_BW = {pd['runtime_peak_bw_mb_s'] / 1e3:.0f} GB/s (:84) is only "
                        f"the runtime-reported figure",
                 "clock_hz": "VX_config.toml:85 default 400 MHz (cycle-level results do not depend on it)"})


PSBASE_PARAMS = PS_ROOT / "results" / "P3.1" / "machine_params.csv"


def vortex_psbase(cores: int, path: Path = PSBASE_PARAMS) -> Machine:
    """MEASURED PS-BASE-S1-<cores>c machine. Peaks are the best measured rates, not structural bounds:
    fpu = ps_memprobe -m fma (8 independent FMA chains per thread), tcu = stock sgemm_tcu_wg_dxa at K = 64 (largest
    M = N run), dram_bytes_per_cycle = ps_memprobe -m stream over 32 MiB (LSU path, achievable, below the model's
    channel peak; at 16 cores the stream's latency builds up on-chip, between the LSU and the DRAM model (resource not
    identified), so it is a lower bound on DRAM bandwidth, labelled in the source string from the CSV's `stream_limit`). Clock = the configuration's 400 MHz (cycle-level results do not
    depend on it)."""
    with open(path) as f:
        row = next(r for r in csv.DictReader(f) if r["config"] == f"PS-BASE-S1-{cores}c")
    src = f"measured: results/P3.1/machine_params.csv (PS-BASE-S1-{cores}c"
    return Machine(
        name=f"psbase-S1-{cores}c", clock_hz=float(row["clock_mhz"]) * 1e6,
        flops_per_cycle={"fpu": float(row["fpu_flop_per_cycle"]), "tcu": float(row["tcu_flop_per_cycle"])},
        dram_bytes_per_cycle=float(row["stream_bytes_per_cycle"]), measured=True,
        sources={"fpu": f"{src}, ps_memprobe -m fma; structural {row['fpu_structural_flop_per_cycle']})",
                 "tcu": f"{src}, sgemm_tcu_wg_dxa {row['tcu_best_args']}; structural "
                        f"{row['tcu_structural_flop_per_cycle']})",
                 "dram_bytes_per_cycle": f"{src}, ps_memprobe -m stream 32 MiB; channel peak "
                                         f"{row['dram_peak_bytes_per_cycle']} B/cycle"
                                         + (f"; LOWER BOUND on DRAM bandwidth: not DRAM-bound, stream latency builds up "
                                            f"{'on-chip between the LSU and the DRAM (resource not identified)' if row.get('stream_limit') == 'on_chip' else 'at the per-core LSU in-flight cap'}"
                                            f", methodology §11.4)" if row.get("stream_limit") in ("on_chip", "lsu_cap") else ")"),
                 "clock_hz": f"{src}; VX_CFG_PLATFORM_CLOCK_RATE default 400 MHz)"})


def _profile(name: str) -> dict:
    return json.loads((PROFILES / f"{name}.json").read_text())


def gpu_like(profile: str, fp32_lanes_per_sm: int, tensor_fma_per_sm: int) -> Machine:
    """GPU-like machine from a Vortex profile: SM count = VX_CFG_NUM_CORES (one Vortex core per SM), clock =
    VX_CFG_PLATFORM_CLOCK_RATE (MHz), BW = VX_CFG_PLATFORM_MEMORY_PEAK_BW (MB/s); the profile's `sources` block
    cites the vendor whitepaper/datasheet for these. FPU and TCU per-SM rates are arguments, marked assumptions."""
    p = _profile(profile)
    sms = p["chip"]["VX_CFG_NUM_CORES"]
    clk = p["platform"]["VX_CFG_PLATFORM_CLOCK_RATE"] * 1e6
    bw = p["platform"]["VX_CFG_PLATFORM_MEMORY_PEAK_BW"] * 1e6
    src = f"third_party/vortex/profiles/{profile}.json"
    return Machine(
        name=f"{profile}-like", clock_hz=clk,
        flops_per_cycle={"fpu": sms * fp32_lanes_per_sm * 2, "tcu": sms * tensor_fma_per_sm * 2},
        dram_bytes_per_cycle=bw / clk, measured=False,
        sources={"clock_hz": f"{src} VX_CFG_PLATFORM_CLOCK_RATE", "dram_bytes_per_cycle":
                 f"{src} VX_CFG_PLATFORM_MEMORY_PEAK_BW / clock", "cores": f"{src} VX_CFG_NUM_CORES = {sms} SMs",
                 "fpu": f"assumption: {fp32_lanes_per_sm} FP32 FMA lanes per SM",
                 "tcu": f"assumption: {tensor_fma_per_sm} dense FP16 tensor FMA per SM per cycle (profiles have the "
                        f"TCU off, R§7; not verified against a ledger source)"})


def machines() -> dict[str, Machine]:
    """The machine set. Per-SM assumptions for the GPU-like machines: A100 64 FP32 lanes and 1024 dense FP16
    tensor FMA per SM per cycle; H100 128 FP32 lanes and 2048 tensor FMA (twice A100 per SM). At the profile clocks
    these give 19.5 / 311.9 TFLOP/s (A100) and 66.9 / 1070.5 TFLOP/s (H100) — the commonly quoted dense peaks, scaled
    to the profile's 1980 MHz for H100; treat them as assumptions until a source is added to refs/CITATIONS.md."""
    ms = [vortex_s1(4), vortex_s1(8), vortex_s1(16), gpu_like("a100", 64, 1024), gpu_like("h100", 128, 2048)]
    if PSBASE_PARAMS.is_file():   # measured machines (results/<run>/machine_params.csv)
        ms += [vortex_psbase(c) for c in (4, 8, 16)]
    return {m.name: m for m in ms}


# ------------------------------------------------------------------------------------------------- equations


def attainable(ai: float, peak: float, bw: float) -> float:
    """E7: Perf = min(Peak_FLOPs, AI × Peak_BW)."""
    return min(peak, ai * bw)


def ai_linear(n_tok: float, d_in: float, d_out: float, q_w: float, q_a: float) -> float:
    """E2 exact: AI = 2·N_tok / (q_w + q_a·N_tok·(1/d_in + 1/d_out)) (FLOP/byte)."""
    return 2 * n_tok / (q_w + q_a * n_tok * (1 / d_in + 1 / d_out))


def ai_linear_small_batch(n_tok: float, q_w: float) -> float:
    """E2 limit for N_tok ≪ d: AI ≈ 2·N_tok / q_w."""
    return 2 * n_tok / q_w


def ai_attn_decode(g: float, q: float) -> float:
    """E5: decode-attention AI = 4·T·H_q·D_h / (2·T·H_KV·D_h·q) = 2g/q."""
    return 2 * g / q


def decode_step_lb(m: opgen.ModelShape, B: int, T: int, machine: Machine, q_w: float = 2, q: float = 2,
                   act: float = 0.0, unit: str = "tcu") -> dict:
    """E6: t_step ≥ max{(q_w·N_params + M_KV,total + act)/BW, (2·B·N_params + 4·B·L·T·d)/FLOPS_peak}.
    M_KV,total = E3 with B sequences of T cached tokens (sliding windows and MLA via opgen.kv_bytes_total).
    Returns both terms and the bound (seconds)."""
    npar = opgen.n_params(m)
    mem = (q_w * npar + opgen.kv_bytes_total(m, [T] * B, q) + act) / machine.bw
    comp = (2 * B * npar + 4 * B * m.L * T * m.d) / machine.peak(unit)
    return dict(t_mem=mem, t_comp=comp, t_step=max(mem, comp), bound="memory" if mem >= comp else "compute")


def kv_weight_crossover_bt(m: opgen.ModelShape, q_w: float = 2, q: float = 2, n_params: float | None = None) -> float:
    """E6 crossover: KV traffic = weight traffic when B·T·M_KV/token = q_w·N_params, i.e.
    B·T = q_w·N_params / M_KV/token (ignores sliding windows: valid while T ≤ window). N_params defaults to
    opgen.n_params (all weights; for MoE the weights actually streamed per step are fewer, so the true crossover is
    lower); `n_params` overrides it (e.g. R§1's round 7×10⁹)."""
    npar = opgen.n_params(m) if n_params is None else n_params
    return q_w * npar / opgen.kv_bytes_per_token(m, q)


def rho_kv(m: opgen.ModelShape, contexts: Iterable[int], q_w: float = 2, q: float = 2,
           weight_bytes: float | None = None) -> float:
    """Methodology §4 region test: ρ_KV = M_KV,total / (weight bytes per step); a decode iteration is KV-bound iff
    ρ_KV ≥ 1. Default weight bytes = q_w·N_params (dense models). For MoE models pass the bytes actually streamed in
    that step (`weight_bytes`, e.g. opgen.totals(ops)["w_rd"]): only the touched experts are read (methodology §4)."""
    wb = q_w * opgen.n_params(m) if weight_bytes is None else weight_bytes
    return opgen.kv_bytes_total(m, contexts, q) / wb


def op_unit(op: opgen.Op, machine: Machine) -> str:
    """Unit an op runs on in this model: GEMM-like ops (linear, attention matmuls) on the TCU when the machine has
    one, everything else (elementwise, embedding gather) on the FPU/SIMT lanes."""
    return "tcu" if op.kind in ("linear", "attn") and "tcu" in machine.flops_per_cycle else "fpu"


def op_time_lb(op: opgen.Op, machine: Machine) -> dict:
    """Per-op roofline bound (E7 applied to one op, compulsory bytes): t ≥ max(FLOPs/peak, bytes/BW)."""
    unit = op_unit(op, machine)
    tc, tm = op.flops / machine.peak(unit), op.bytes / machine.bw
    return dict(unit=unit, t_comp=tc, t_mem=tm, t=max(tc, tm), bound="compute" if tc > tm else "memory",
                ai=op.ai, ridge=machine.ridge(unit), perf=attainable(op.ai, machine.peak(unit), machine.bw))


# ------------------------------------------------------------------------------------------------- plots


PHASES = ["prefill", "mixed", "decode B=16", "decode B=1"]
CLASS_STYLE = {"linear": ("#2a78d6", "o", 0.18), "attn": ("#eb6834", "s", 0.0), "elementwise": ("#1baf7a", "^", -0.18)}


def plot_points(m: opgen.ModelShape, q: float) -> list[dict]:
    """AI of layer-0 ops (+ LM head) per phase scenario for one model (the points the figures draw)."""
    cap = m.max_seq or 1 << 30
    S, T, C = min(512, cap), min(4096, cap), min(256, cap)
    scen = {"prefill": opgen.prefill(1, S), "decode B=1": opgen.decode(1, min(512, cap)),
            "decode B=16": opgen.decode(16, T), "mixed": opgen.mixed([(C, 0)], [(15, T)])}
    pts = []
    for ph, seqs in scen.items():
        for o in opgen.gen_ops(m, seqs, q_w=q, q_a=q, q=q, layers=[0]):
            if o.layer in (0, m.L) and o.bytes > 0 and o.flops > 0:
                pts.append(dict(model=m.name, phase=ph, op=o.name, kind=o.kind, flops=o.flops, bytes=o.bytes, ai=o.ai))
    return pts


def plot_roofline(m: opgen.ModelShape, q: float, mset: list[Machine], path: Path) -> list[dict]:
    """AI by op and phase (one row per phase, op class by colour and marker), with each machine's E7 ridge points
    (TCU solid, FPU dashed) as vertical lines: an op left of a ridge is bandwidth-bound on that unit. AI does not
    depend on the machine, so one axis serves all machines; the attainable FLOP/s per machine is in the CSV."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    pts = plot_points(m, q)
    fig, ax = plt.subplots(figsize=(10, 4.8), constrained_layout=True)
    rows = []
    for p in pts:
        col, mk, dy = CLASS_STYLE[p["kind"]]
        ax.scatter(p["ai"], PHASES.index(p["phase"]) + dy, s=42, marker=mk, color=col, edgecolors="white",
                   linewidths=1, zorder=3)
        for mc in mset:
            unit = op_unit(opgen.Op(0, p["op"], p["kind"], 0, 0, 0, 0, 0.0), mc)
            rows.append(dict(p, machine=mc.name, unit=unit, ridge=mc.ridge(unit),
                             perf_flops_s=attainable(p["ai"], mc.peak(unit), mc.bw),
                             bound="memory" if p["ai"] < mc.ridge(unit) else "compute"))
    grays = ["#8a8983", "#52514e", "#1a1a19"]
    for i, (g, mc) in enumerate(zip(grays, mset)):
        for unit, ls in (("tcu", "-"), ("fpu", "--")):
            ax.axvline(mc.ridge(unit), color=g, lw=1.2, ls=ls, zorder=1)
        star = "" if mc.measured else "*"
        ax.text(mc.ridge("tcu"), len(PHASES) - 0.55 + 0.32 * i, f"{mc.name}{star}\nTCU {mc.ridge('tcu'):.0f}", fontsize=7,
                ha="center", va="bottom", color=g)
    ax.set_xscale("log")
    ax.set_yticks(range(len(PHASES)), PHASES)
    ax.set_ylim(-0.6, len(PHASES) + 0.6)
    ax.set_xlabel("arithmetic intensity (FLOP/byte, compulsory bytes; E2/E5)")
    ax.grid(True, axis="x", which="major", color="#e8e7e2", lw=0.6)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    handles = [Line2D([], [], color=c, marker=mk, ls="", label=k) for k, (c, mk, _) in CLASS_STYLE.items()]
    handles += [Line2D([], [], color="#52514e", ls="-", label="TCU ridge"),
                Line2D([], [], color="#52514e", ls="--", label="FPU ridge")]
    ax.legend(handles=handles, loc="center left", bbox_to_anchor=(1.01, 0.5), fontsize=8, frameon=False)
    ax.set_title(f"{m.name}: AI of layer-0 ops + LM head by phase (q = {q} B)\nRidges (FLOP/B): "
                 + ", ".join(f"{mc.name} TCU {mc.ridge('tcu'):.1f} / FPU {mc.ridge('fpu'):.2f}" for mc in mset)
                 + "\n* unmeasured placeholder; GPU-like TCU/FPU peaks are assumptions", fontsize=8)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description="roofline figures, machine table and E6 crossovers")
    ap.add_argument("--out", default="results/P1.2")
    a = ap.parse_args(argv)
    out = Path(a.out)
    (out / "fig").mkdir(parents=True, exist_ok=True)
    ms = machines()
    with open(out / "machines.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["machine", "measured", "clock_hz", "fpu_flop_per_cycle", "tcu_flop_per_cycle",
                    "dram_bytes_per_cycle", "bw_bytes_s", "peak_tcu_flop_s", "peak_fpu_flop_s", "ridge_tcu",
                    "ridge_fpu", "sources"])
        for mc in ms.values():
            w.writerow([mc.name, mc.measured, mc.clock_hz, mc.flops_per_cycle["fpu"], mc.flops_per_cycle["tcu"],
                        mc.dram_bytes_per_cycle, mc.bw, mc.peak("tcu"), mc.peak("fpu"), f"{mc.ridge('tcu'):.4f}",
                        f"{mc.ridge('fpu'):.4f}", " | ".join(f"{k}: {v}" for k, v in mc.sources.items())])
    # E6 crossover per model (bf16 weights + KV for HF configs, fp32 for llama2.c)
    shapes = [(opgen.from_llama2c_bin(PS_ROOT / "data" / "models" / f"{b}.bin"), 4) for b in ("stories260K", "stories15M")]
    shapes += [(opgen.from_hf_config(p), 2) for p in sorted((PS_ROOT / "configs").glob("*.json"))]
    with open(out / "crossover.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["model", "q_w", "q", "n_params", "kv_bytes_per_token", "crossover_BT", "attn_decode_ai_E5"])
        for m, qb in shapes:
            w.writerow([m.name, qb, qb, opgen.n_params(m), opgen.kv_bytes_per_token(m, qb),
                        f"{kv_weight_crossover_bt(m, qb, qb):.1f}",
                        "" if m.is_mla else f"{ai_attn_decode(m.g, qb):.3f}"])
