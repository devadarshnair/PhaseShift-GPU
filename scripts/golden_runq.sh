#!/usr/bin/env bash
# PhaseShift: build runq_tokens and record the Q8_0 golden token file. Run inside one lowload job:
#   $LL --rss 0.5 --mem 2 --label:runq_tokens --log results/<run>/logs/golden_runq.log -- scripts/golden_runq.sh
#
# The clone third_party/llama2.c stays read-only: runq.c is COPIED to build/llama2c/src/runq_tokens.c, patched with
# patches/llama2c/runq_tokens.patch (one fprintf(stderr, "PS_TOK ...") per forward step, no computation changed, same as
# the run_tokens patch) and compiled there with the golden-build flags (gcc -O3 ... -lm: no -Ofast / -ffast-math, no OpenMP).
# Flags verified from runq.c main()/error_usage: -t temperature (0 = greedy argmax), -n steps, -i prompt, -z tokenizer path.
#   build/llama2c/runq        <model_q80.bin> -z <tokenizer.bin> -t 0 -n 200 -i "Once upon a time"   (stdout)
#   build/llama2c/runq_tokens the same command with the patch; its stdout must equal runq's byte for byte.
# Output: results/<run>/golden_tokens_15M_q80.txt in the golden-file format (header comments, then `pos token next forced`) and
# results/<run>/golden_15M_q80.txt (the text). Refuses to overwrite a different existing file. Writes
# build/llama2c/BUILDINFO.runq_tokens (the golden build's BUILDINFO is not touched).
set -euo pipefail
PS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PS"
SRC="$PS/third_party/llama2.c"; B="$PS/build/llama2c"; OUT=results/EP.2; LOGS=$OUT/logs
MODEL=build/models/stories15M_q80.bin; TOK=third_party/llama2.c/tokenizer.bin
mkdir -p "$B/src" "$LOGS"
cp -f "$SRC/runq.c" "$B/src/runq_tokens.c"
patch --quiet --no-backup-if-mismatch "$B/src/runq_tokens.c" "$PS/patches/llama2c/runq_tokens.patch"
gcc -O3 -o "$B/runq_tokens" "$B/src/runq_tokens.c" -lm
{
    echo "llama2.c commit: $(git --no-optional-locks -C "$SRC" rev-parse HEAD)"
    echo "gcc: $(gcc --version | head -1)"
    echo "CFLAGS: -O3  LDLIBS: -lm"
    (cd "$B" && sha256sum src/runq_tokens.c runq_tokens runq)
} > "$B/BUILDINFO.runq_tokens"
args=("$MODEL" -z "$TOK" -t 0 -n 200 -i "Once upon a time")
"$B/runq" "${args[@]}" > "$LOGS/golden_15M_q80.run1.txt" 2> "$LOGS/golden_15M_q80.run1.err"
"$B/runq" "${args[@]}" > "$LOGS/golden_15M_q80.run2.txt" 2> "$LOGS/golden_15M_q80.run2.err"
cmp "$LOGS/golden_15M_q80.run1.txt" "$LOGS/golden_15M_q80.run2.txt"
[ -s "$LOGS/golden_15M_q80.run1.txt" ] || { echo "empty golden" >&2; exit 1; }
"$B/runq_tokens" "${args[@]}" > "$LOGS/golden_15M_q80.tok.txt" 2> "$LOGS/golden_15M_q80.tok.err"
cmp "$LOGS/golden_15M_q80.run1.txt" "$LOGS/golden_15M_q80.tok.txt"
tmp="$LOGS/golden_tokens_15M_q80.new"
{
    echo "# runq (llama2.c Q8_0) golden token ids, generated by scripts/golden_runq.sh"
    echo "# cmd: build/llama2c/runq_tokens ${args[*]:0:5} -n 200 -i \"Once upon a time\""
    echo "# llama2.c $(git --no-optional-locks -C "$SRC" rev-parse HEAD); model sha256 $(sha256sum "$MODEL" | cut -c1-64) (stories15M_q80.bin, GS read from its header); tokenizer sha256 $(sha256sum "$TOK" | cut -c1-64)"
    echo "# columns: pos token next forced   (forced=1: next taken from the prompt; 0: greedy argmax)"
    grep '^PS_TOK ' "$LOGS/golden_15M_q80.tok.err" | cut -d' ' -f2-
} > "$tmp"
for f in golden_15M_q80.txt golden_tokens_15M_q80.txt; do
    src="$LOGS/golden_15M_q80.run1.txt"; [ "$f" = "golden_tokens_15M_q80.txt" ] && src="$tmp"
    if [ -e "$OUT/$f" ]; then cmp "$OUT/$f" "$src" || { echo "REFUSE: $OUT/$f differs from the new run" >&2; exit 1; }
    else cp "$src" "$OUT/$f"; fi
done
rm -f "$tmp"
echo "15M_q80: $(wc -c < "$OUT/golden_15M_q80.txt") B text, $(grep -vc '^#' "$OUT/golden_tokens_15M_q80.txt") steps, $(cat "$LOGS/golden_15M_q80.run1.err")"
