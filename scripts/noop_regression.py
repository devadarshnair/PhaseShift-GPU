#!/usr/bin/env python3
"""noop_regression.py -- PhaseShift no-op regression (created). Wrapper: scripts/noop_regression.sh.

  noop_regression.py run     --step <ID> [--reg experiments/noop_regression.yaml] [--all] [--dry-run]
  noop_regression.py compare --step <ID> [--reg ...] [--all]

--all extends REG by (1) every P2 kernel cell of experiments/knobs.yaml (`kernels:`) at its machine
         (PS-BASE-S1-4c, perf 1) on both trees, and (2) per P2 kernel an "all modes 0" ps run: an explicit host write of
         the all-zero way-mask block (`-W 0x0:0x0`, i.e. a full [dcr_phase] block at reset values) plus a PS_SCHEDULE
         that sets every schedulable knob to 0 at work 0 (results/<ID>/sched/zero.sched); each zero run must equal the
         BASE row of the same kernel without those arguments (tags reg=zero, ref_args). Pass = every entry identical.

run      writes results/<ID>/noop_regression.batch.yaml (the REG list with `step: <ID>`), runs it with
         `vxrun.py batch` (serial; every SimX job through lowload.sh; finished run keys are skipped), then compares.
compare  for every REG entry (app, args, config/configs, perf, env) picks, per tree, the newest status-ok row of
         results/<ID>/rows.jsonl whose tree fingerprint equals the tree's CURRENT fingerprint (so a ps row measured
         before the latest patch edit can never stand in for the current patch), and requires identical `instrs` and
         `cycles` on base and ps. For out-of-tree ps_* apps the row's app-source hash must also be the current one. Writes results/<ID>/noop_regression.csv; exit 0 iff every entry has both rows and
         all are identical, 1 otherwise (a missing row counts as a failure), 75 if the batch was DEFERRED.

Why "identical" and not "within noise": SimX is deterministic for a fixed launch sequence (methodology §2,
consequence 5), and both trees run the same app binary sources with the same CONFIGS, so any difference is caused by
the patch.
"""
from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vxrun  # noqa: E402

PS = vxrun.PS
DEFAULT_REG = PS / "experiments" / "noop_regression.yaml"
FIELDS = ["reg", "app", "args", "config", "configs_canonical", "perf", "env", "base_instrs", "ps_instrs",
          "base_cycles", "ps_cycles", "identical", "base_run_key", "ps_run_key", "note"]


def load_reg(path: Path) -> dict:
    import yaml
    doc = yaml.safe_load(path.read_text()) or {}
    if not doc.get("runs"):
        raise SystemExit(f"noop_regression: {path} has no runs")
    return doc


def batch_doc(reg: dict, step: str) -> dict:
    return {"step": step, **{k: v for k, v in reg.items() if k != "step"}}


ZERO_KNOBS = (["mode", "insert", "dram_sched", "dram_aging", "dxa_fdp", "l2_ucp", "range_acct_only"]
              + [f"dxa_depth{c}" for c in range(8)])


def extend_all(reg: dict, step: str) -> dict:
    """REG + the P2 kernels of experiments/knobs.yaml (both trees) + their all-modes-0 ps runs (see --all above)."""
    import knobs
    kdoc = knobs.load()
    sched = PS / "results" / step / "sched" / "zero.sched"
    sched.parent.mkdir(parents=True, exist_ok=True)
    sched.write_text("# GENERATED by scripts/noop_regression.py --all: every schedulable [dcr_phase] knob at its reset "
                     "value (0) from work 0\n0 " + " ".join(f"{k}=0" for k in ZERO_KNOBS) + "\n")
    runs = list(reg["runs"])
    for k in knobs.kernels(kdoc):
        runs.append({"app": k["app"], "args": k["args"], "config": kdoc["machine"], "tags": {"reg": "p2", "kernel": k["id"]}})
        runs.append({"app": k["app"], "args": k["args"] + " -W 0x0:0x0", "config": kdoc["machine"], "tree": "ps",
                     "env": {"PS_SCHEDULE": str(sched), "PS_SCHEDULE_UNIT": "instrs"},
                     "tags": {"reg": "zero", "kernel": k["id"], "ref_args": k["args"]}})
    return dict(reg, runs=runs)


def entries(reg: dict, named: dict) -> list[dict]:
    """Expanded REG specs for the ps tree only (one per comparison), resolved like vxrun does."""
    out = []
    for spec in vxrun.expand_batch(batch_doc(reg, "x"), named):
        if spec.get("tree") != "ps":
            continue
        out.append(spec)
    return out


def _cmp_key(r: dict) -> tuple:
    return (r["app"], r["args"], tuple(r["configs_canonical"]), int(r["perf"]),
            json.dumps(r.get("env") or {}, sort_keys=True))


def _as_set(h):
    return {h} if isinstance(h, str) else set(h)


def compare(rows: list[dict], specs: list[dict], fps: dict, named: dict, app_hash=None) -> list[dict]:
    """One result per spec. rows: rows.jsonl content; fps: {'base': fp, 'ps': fp} current tree fingerprints;
    app_hash(tree, app) -> current app-source hash ('' for in-tree apps; None = do not check)."""
    newest = {}
    for r in rows:   # file order = append order, so later rows win
        if r.get("status") != "ok" or r.get("tree") not in fps or r.get("tree_fp") != fps[r["tree"]]:
            continue
        if app_hash is not None and r.get("app_src_hash", "") not in _as_set(app_hash(r["tree"], r["app"])):
            continue
        newest[(r["tree"],) + _cmp_key(r)] = r
    out = []
    for spec in specs:
        s = vxrun.resolve(spec, named)
        key = _cmp_key({"app": s["app"], "args": s["args"], "configs_canonical": s["configs_canonical"],
                        "perf": s["perf"], "env": s["env"]})
        tags = s.get("tags") or {}
        bkey = key
        if tags.get("reg") == "zero":   # --all: compare the all-modes-0 ps run with the plain base run of the kernel
            bkey = _cmp_key({"app": s["app"], "args": tags["ref_args"], "configs_canonical": s["configs_canonical"],
                             "perf": s["perf"], "env": {}})
        b, p = newest.get(("base",) + bkey), newest.get(("ps",) + key)
        res = {"reg": (s.get("tags") or {}).get("reg", ""), "app": s["app"], "args": s["args"],
               "config": s.get("config") or "", "configs_canonical": " ".join(s["configs_canonical"]),
               "perf": s["perf"], "env": json.dumps(s["env"], sort_keys=True),
               "base_instrs": b and b["instrs"], "ps_instrs": p and p["instrs"],
               "base_cycles": b and b["cycles"], "ps_cycles": p and p["cycles"],
               "base_run_key": b and b["run_key"][:12], "ps_run_key": p and p["run_key"][:12], "note": ""}
        if b is None or p is None:
            res["identical"] = False
            res["note"] = "missing " + " and ".join(t for t, x in (("base", b), ("ps", p)) if x is None) + " row"
        else:
            res["identical"] = (b["instrs"] == p["instrs"]) and (b["cycles"] == p["cycles"])
            if not res["identical"]:
                res["note"] = (f"instrs {p['instrs'] - b['instrs']:+d}, cycles {p['cycles'] - b['cycles']:+d} "
                               "(ps - base)")
        out.append(res)
    return out


def write_csv(path: Path, results: list[dict]) -> None:
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for r in results:
            w.writerow(r)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["run", "compare"])
    ap.add_argument("--step", required=True)
    ap.add_argument("--reg", type=Path, default=DEFAULT_REG)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--all", action="store_true", help="REG + every P2 kernel + all-modes-0 runs")
    a = ap.parse_args(argv)
    reg = load_reg(a.reg)
    if a.all:
        reg = extend_all(reg, a.step)
    named = vxrun.load_named_configs()
    d = PS / "results" / a.step
    d.mkdir(parents=True, exist_ok=True)
    dec = PS / "kernels" / "decode_attn_gqa" / "main.cpp"
    if dec.exists() and not any("decode_attn" in str(r.get("app", "")) for r in reg["runs"]):
        print(f"noop_regression: WARNING: {dec.relative_to(PS)} exists but REG has no ps_decode_attn entry "
              "(add it, built with -DPS_HINTS=0)")
    if a.cmd == "run":
        import yaml
        bpath = d / "noop_regression.batch.yaml"
        bpath.write_text("# GENERATED by scripts/noop_regression.py from " + str(a.reg.relative_to(PS)
                         if a.reg.is_relative_to(PS) else a.reg) + "\n" + yaml.safe_dump(batch_doc(reg, a.step),
                                                                                       sort_keys=False))
        cmd = [sys.executable, "-B", str(PS / "scripts" / "vxrun.py"), "batch", str(bpath)]
        if a.dry_run:
            cmd.append("--dry-run")
        rc = subprocess.run(cmd).returncode
        if a.dry_run:
            return rc
        if rc == vxrun.DEFERRED:
            print("noop_regression: DEFERRED (machine busy); re-run later, finished runs are skipped")
            return vxrun.DEFERRED
    rows = vxrun.RowStore(d / "rows.jsonl").load()
    fps = {t: vxrun.tree_fingerprint(t) for t in ("base", "ps")}
    hashes = {}

    def app_hash(tree, app):
        if (tree, app) not in hashes:
            bdir = PS / "build" / f"vortex-{tree}"   # D1: v4 rows carry app_dep_hash, older rows the legacy hash
            hashes[(tree, app)] = (vxrun.app_dep_hash(app, bdir), vxrun.app_source_hash(app, bdir))
        return hashes[(tree, app)]

    results = compare(rows, entries(reg, named), fps, named, app_hash)
    write_csv(d / "noop_regression.csv", results)
    ok = all(r["identical"] for r in results)
    for r in results:
        print(f"noop_regression: {'IDENTICAL' if r['identical'] else 'DIFFERENT'} [{r['reg']}] {r['app']} "
              f"{r['args']!r} [{r['config']}] base {r['base_instrs']}/{r['base_cycles']} "
              f"ps {r['ps_instrs']}/{r['ps_cycles']} {r['note']}")
    print(f"noop_regression: {'PASS' if ok else 'FAIL'} ({sum(r['identical'] for r in results)}/{len(results)} "
          f"identical) -> {(d / 'noop_regression.csv').relative_to(PS)}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
