"""PhaseShift roofline model: E2, E5, E6, E7 of `docs/methodology.md` §2 on machine descriptions.

A machine is (peak FLOP/cycle per unit type, DRAM bytes/cycle, clock). Ridge (E7) = peak FLOP/s ÷ BW = peak
FLOP/cycle ÷ DRAM bytes/cycle (FLOP/byte). Every machine number carries its source in `Machine.sources`, or says
"assumption". Machines:

  * `vortex-S1-{4,8,16}c` — UNMEASURED placeholders derived from the Vortex 3.0 configuration file
    (third_party/vortex/VX_config.toml) at the tier configuration (NUM_THREADS = 32, NUM_WARPS = 8, L2 on);
    replaces them with measured PS-BASE numbers (methodology §11).
  * `psbase-S1-{4,8,16}c` — MEASURED PS-BASE machines (methodology §11): FPU / TCU FLOP per cycle and the
    achievable DRAM bytes per cycle measured on SimX at the PS-BASE configurations (results/<run>/machine_params.csv,
    regenerated by results/<run>/summarize.py). They replace the `vortex-S1-*` placeholders for every use;
    the placeholders stay only so the evidence remains reproducible.
  * `a100-like`, `h100-like` — core count, clock and DRAM bandwidth from the Vortex profiles
    third_party/vortex/profiles/{a100,h100}.json (which cite the NVIDIA whitepapers/datasheet); FPU and tensor-core
    peaks are ASSUMPTIONS (the profiles have the TCU off, R§7) stated per SM below.

Units throughout: FLOP, bytes, cycles, seconds (FLOP/s and bytes/s for rates).
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

from model import opgen

PS_ROOT = Path(__file__).resolve().parents[1]
PROFILES = PS_ROOT / "third_party" / "vortex" / "profiles"


@dataclass(frozen=True)
class Machine:
    """flops_per_cycle: whole-chip peak FLOP/cycle per unit type ("fpu" = FP32 SIMT lanes, "tcu" = FP16 tensor
    unit); dram_bytes_per_cycle: whole-chip DRAM bytes per core-clock cycle; clock_hz: core clock."""

    name: str
    clock_hz: float
    flops_per_cycle: dict
    dram_bytes_per_cycle: float
    measured: bool = False
    sources: dict = field(default_factory=dict)

    @property
    def bw(self) -> float:
        """Peak DRAM bandwidth BW in bytes/s."""
        return self.dram_bytes_per_cycle * self.clock_hz

    def peak(self, unit: str = "tcu") -> float:
        """FLOPS_peak in FLOP/s of the given unit type (falls back to "fpu" if the machine has no such unit)."""
        return self.flops_per_cycle.get(unit, self.flops_per_cycle["fpu"]) * self.clock_hz

    def ridge(self, unit: str = "tcu") -> float:
        """E7 ridge point = Peak_FLOPs / Peak_BW (FLOP/byte); clock-independent (= FLOP/cycle ÷ bytes/cycle)."""
        return self.peak(unit) / self.bw


