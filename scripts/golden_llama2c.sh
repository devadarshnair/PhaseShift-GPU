#!/usr/bin/env bash
# PhaseShift: llama2.c golden runs. Run after scripts/build_llama2c.sh, e.g. inside the same
# lowload.sh job:  $LL --rss 0.5 --mem 2 --label S8-llama2c -- bash -c 'scripts/build_llama2c.sh && scripts/golden_llama2c.sh'
#
# Flags verified from run's usage text (run.c error_usage): -t temperature (0 = greedy argmax, so no RNG is used),
# -n steps, -i prompt, -z tokenizer path.
#   260K: build/llama2c/run data/models/stories260K.bin -z data/models/tok512.bin            -t 0 -n 200 -i "Once upon a time"
#   15M : build/llama2c/run data/models/stories15M.bin  -z third_party/llama2.c/tokenizer.bin -t 0 -n 200 -i "Once upon a time"
# Each run twice; the two stdouts must be byte-identical -> results/S8/golden_<m>.txt (stdout only; run prints the
# "achieved tok/s" line on stderr, kept in results/S8/logs/). The same command with build/llama2c/run_tokens must
# give the identical stdout; its PS_TOK stderr lines become results/S8/golden_tokens_<m>.txt:
#   header comment lines, then one line per forward step: pos token next forced   (forced = 1 while the next token is
#   taken from the prompt, 0 when it was produced by argmax). The full sequence is token[0] followed by every next.
# Exit non-zero on any mismatch. Idempotent: if golden_<m>.txt already exists it must equal the new output (never
# silently rewritten).
set -euo pipefail
PS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PS"
OUT=results/S8; LOGS=$OUT/logs; mkdir -p "$LOGS"
PROMPT="Once upon a time"
declare -A MODEL=( [260K]=data/models/stories260K.bin [15M]=data/models/stories15M.bin )
declare -A TOK=(   [260K]=data/models/tok512.bin      [15M]=third_party/llama2.c/tokenizer.bin )
for m in 260K 15M; do
    args=("${MODEL[$m]}" -z "${TOK[$m]}" -t 0 -n 200 -i "$PROMPT")
    build/llama2c/run "${args[@]}" > "$LOGS/golden_${m}.run1.txt" 2> "$LOGS/golden_${m}.run1.err"
    build/llama2c/run "${args[@]}" > "$LOGS/golden_${m}.run2.txt" 2> "$LOGS/golden_${m}.run2.err"
    cmp "$LOGS/golden_${m}.run1.txt" "$LOGS/golden_${m}.run2.txt"
    [ -s "$LOGS/golden_${m}.run1.txt" ] || { echo "empty golden for $m" >&2; exit 1; }
    build/llama2c/run_tokens "${args[@]}" > "$LOGS/golden_${m}.tok.txt" 2> "$LOGS/golden_${m}.tok.err"
    cmp "$LOGS/golden_${m}.run1.txt" "$LOGS/golden_${m}.tok.txt"
    tmp="$LOGS/golden_tokens_${m}.new"
    {
        echo "# llama2.c golden token ids, generated by scripts/golden_llama2c.sh"
        echo "# cmd: build/llama2c/run_tokens ${args[*]:0:7} -i \"$PROMPT\""
        echo "# llama2.c $(git --no-optional-locks -C third_party/llama2.c rev-parse HEAD); model sha256 $(sha256sum "${MODEL[$m]}" | cut -c1-64); tokenizer sha256 $(sha256sum "${TOK[$m]}" | cut -c1-64)"
        echo "# columns: pos token next forced   (forced=1: next taken from the prompt; 0: greedy argmax)"
        grep '^PS_TOK ' "$LOGS/golden_${m}.tok.err" | cut -d' ' -f2-
    } > "$tmp"
    for f in golden_${m}.txt golden_tokens_${m}.txt; do
        src="$LOGS/golden_${m}.run1.txt"; [ "$f" = "golden_tokens_${m}.txt" ] && src="$tmp"
        if [ -e "$OUT/$f" ]; then cmp "$OUT/$f" "$src" || { echo "REFUSE: $OUT/$f differs from the new run" >&2; exit 1; }
        else cp "$src" "$OUT/$f"; fi
    done
    rm -f "$tmp"
    echo "$m: $(wc -c < "$OUT/golden_${m}.txt") B text, $(grep -vc '^#' "$OUT/golden_tokens_${m}.txt") steps, $(cat "$LOGS/golden_${m}.run1.err")"
done
